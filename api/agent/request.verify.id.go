//||------------------------------------------------------------------------------------------------||
//|| Makes the Rabbit MQ request to start the ID verification process
//||------------------------------------------------------------------------------------------------||

package agent

import (
	"api/agent/interfaces"
	"base/db"
	"base/helpers"
	"encoding/base64"
	"encoding/json"
	"fmt"
	"os"
)

//||------------------------------------------------------------------------------------------------||
//|| FetchMedia
//||------------------------------------------------------------------------------------------------||

func FetchMedia(identifier, which string) (interfaces.AgentMedia, error) {

	//||------------------------------------------------------------------------------------------------||
	//|| Create the object name
	//||------------------------------------------------------------------------------------------------||

	bucket := os.Getenv("MINIO_PRIVATE_BUCKET")
	objectName := fmt.Sprintf("verifications/%s/%s", identifier, which)

	//||------------------------------------------------------------------------------------------------||
	//|| Download from MinIO
	//||------------------------------------------------------------------------------------------------||

	data, contentType, err := helpers.MinioDownload(bucket, objectName)
	if err != nil || len(data) == 0 {
		return interfaces.AgentMedia{}, fmt.Errorf("media file not found: %w", err)
	}

	//||------------------------------------------------------------------------------------------------||
	//|| Encode to Base64
	//||------------------------------------------------------------------------------------------------||

	return interfaces.AgentMedia{
		Blob: base64.StdEncoding.EncodeToString(data),
		Mime: contentType,
	}, nil

}

//||------------------------------------------------------------------------------------------------||
//|| Starts the ID verification process
//||------------------------------------------------------------------------------------------------||

func AgentVerifyIDStart(uuid string) error {

	//||------------------------------------------------------------------------------------------------||
	//|| Front
	//||------------------------------------------------------------------------------------------------||

	front, err := FetchMedia(uuid, "front")
	if err != nil {
		return fmt.Errorf("failed to fetch front media: %w", err)
	}

	//||------------------------------------------------------------------------------------------------||
	//|| Back
	//||------------------------------------------------------------------------------------------------||

	back, err := FetchMedia(uuid, "back")
	if err != nil {
		return fmt.Errorf("failed to fetch back media: %w", err)
	}

	//||------------------------------------------------------------------------------------------------||
	//|| Selfie
	//||------------------------------------------------------------------------------------------------||

	selfie, err := FetchMedia(uuid, "selfie")
	if err != nil {
		return fmt.Errorf("failed to fetch selfie media: %w", err)
	}

	//||------------------------------------------------------------------------------------------------||
	//|| Create the Agent Request
	//||------------------------------------------------------------------------------------------------||

	request := interfaces.AgentRequest{
		Identifier: uuid,
		Process:    "PROCESS_VERIFY_ID",
		Media: []interfaces.AgentMedia{
			front,
			back,
			selfie,
		},
		CallBack:  "/internal/verify/id/progress",
		Timestamp: helpers.UniversalNow(),
	}

	//||------------------------------------------------------------------------------------------------||
	//|| JSON
	//||------------------------------------------------------------------------------------------------||

	requestJSON, err := json.Marshal(request)
	if err != nil {
		return fmt.Errorf("failed to marshal request: %w", err)
	}

	//||------------------------------------------------------------------------------------------------||
	//|| Channel
	//||------------------------------------------------------------------------------------------------||

	channel := os.Getenv("RABBITMQ_LEVEL1_CHANNEL")

	//||------------------------------------------------------------------------------------------------||
	//|| Send the request to RabbitMQ
	//||------------------------------------------------------------------------------------------------||

	pubErr := PublishAgentRequest(db.MQChan, channel, requestJSON)
	if pubErr != nil {
		return pubErr
	}

	//||------------------------------------------------------------------------------------------------||
	//|| Success
	//||------------------------------------------------------------------------------------------------||

	return nil
}
