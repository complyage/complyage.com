package public

//||------------------------------------------------------------------------------------------------||
//|| Import
//||------------------------------------------------------------------------------------------------||
import (
	"base/db/models"
	"fmt"
	"net/http"
	"sync"
	"time"

	"github.com/ralphferrara/aria/app"
	"github.com/ralphferrara/aria/responses"
)

//||------------------------------------------------------------------------------------------------||
//|| Cache
//||------------------------------------------------------------------------------------------------||

var (
	cachedVPNs     []models.VPN
	vpnCacheExpiry time.Time
	vpnCacheMutex  sync.Mutex
)

//||------------------------------------------------------------------------------------------------||
//|| Fetch: VPNs From DB
//||------------------------------------------------------------------------------------------------||

func fetchVPNsFromDB() ([]models.VPN, error) {
	var vpns []models.VPN

	result := app.SQLDB["main"].DB.Order("vpn_rating DESC").Find(&vpns)
	if result.Error != nil {
		return nil, fmt.Errorf("failed to fetch vpns from database: %w", result.Error)
	}
	return vpns, nil
}

//||------------------------------------------------------------------------------------------------||
//|| Handler: VPNs (Cached)
//||------------------------------------------------------------------------------------------------||

func VPNHandler(w http.ResponseWriter, r *http.Request) {

	//||------------------------------------------------------------------------------------------------||
	//|| Create Mutex Lock
	//||------------------------------------------------------------------------------------------------||

	vpnCacheMutex.Lock()
	defer vpnCacheMutex.Unlock()

	//||------------------------------------------------------------------------------------------------||
	//|| Cache: Serve if Fresh
	//||------------------------------------------------------------------------------------------------||

	if time.Now().Before(vpnCacheExpiry) && cachedVPNs != nil {
		responses.Success(w, http.StatusOK, cachedVPNs)
		return
	}

	//||------------------------------------------------------------------------------------------------||
	//|| Fetch: From DB
	//||------------------------------------------------------------------------------------------------||

	dbVPNs, err := fetchVPNsFromDB()
	if err != nil {
		responses.Error(w, http.StatusInternalServerError, "Failed to fetch VPNs")
		return
	}

	//||------------------------------------------------------------------------------------------------||
	//|| Cache: Update
	//||------------------------------------------------------------------------------------------------||

	cachedVPNs = dbVPNs
	vpnCacheExpiry = time.Now().Add(15 * time.Minute)

	//||------------------------------------------------------------------------------------------------||
	//|| Respond
	//||------------------------------------------------------------------------------------------------||

	responses.Success(w, http.StatusOK, dbVPNs)
}
