package verifier

//||------------------------------------------------------------------------------------------------||
//|| Import
//||------------------------------------------------------------------------------------------------||

import (
	"fmt"
	"net/http"
	"os"
	"strings"

	"github.com/skip2/go-qrcode"
)

//||------------------------------------------------------------------------------------------------||
//|| Handler: QRCodeGenerate
//|| Endpoint: /v1/api/qr/generate?type=TYPE&identifier=UUID
//|| Generates a QR code pointing to the verification URL
//||------------------------------------------------------------------------------------------------||

func QRCodeGenerate(w http.ResponseWriter, r *http.Request) {

	//||------------------------------------------------------------------------------------------------||
	//|| Get Params
	//||------------------------------------------------------------------------------------------------||

	vtype := r.URL.Query().Get("type")
	identifier := r.URL.Query().Get("identifier")

	//||------------------------------------------------------------------------------------------------||
	//|| Get Params
	//||------------------------------------------------------------------------------------------------||

	if vtype == "" || identifier == "" {
		http.Error(w, "Missing required query parameters", http.StatusBadRequest)
		return
	}

	//||------------------------------------------------------------------------------------------------||
	//|| Get Base URL
	//||------------------------------------------------------------------------------------------------||

	base := os.Getenv("VITE_COMPLYAGE_UI_URL")
	if base == "" {
		http.Error(w, "Missing base URL environment variable", http.StatusInternalServerError)
		return
	}

	//||------------------------------------------------------------------------------------------------||
	//|| Type URL
	//||------------------------------------------------------------------------------------------------||

	uType := "id"
	switch strings.ToLower(vtype) {
	case "iden":
		uType = "id"
	}

	//||------------------------------------------------------------------------------------------------||
	//|| Construct URL
	//||------------------------------------------------------------------------------------------------||

	targetURL := fmt.Sprintf("%s/verification/%s/?identifier=%s", base, uType, identifier)

	//||------------------------------------------------------------------------------------------------||
	//|| Generate QR
	//||------------------------------------------------------------------------------------------------||

	png, err := qrcode.Encode(targetURL, qrcode.Medium, 256)
	if err != nil {
		http.Error(w, "Failed to generate QR code", http.StatusInternalServerError)
		return
	}

	//||------------------------------------------------------------------------------------------------||
	//|| Return PNG
	//||------------------------------------------------------------------------------------------------||

	w.Header().Set("Content-Type", "image/png")
	w.WriteHeader(http.StatusOK)
	w.Write(png)
}
