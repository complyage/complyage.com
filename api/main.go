package main

import (
	"api/handlers"
	"base/adapters"
	"fmt"

	"github.com/joho/godotenv"
	"github.com/ralphferrara/aria/app"
	"github.com/ralphferrara/aria/auth"
	"github.com/ralphferrara/aria/http"
)

//||------------------------------------------------------------------------------------------------||
//|| Main
//||------------------------------------------------------------------------------------------------||

func main() {
	//||------------------------------------------------------------------------------------------------||
	//|| Load Env
	//||------------------------------------------------------------------------------------------------||
	err := godotenv.Load("../.env")
	if err != nil {
		fmt.Println("No .env file found, continuing...")
	}
	//||------------------------------------------------------------------------------------------------||
	//|| Starting switch-over to aria
	//||------------------------------------------------------------------------------------------------||
	app.Init("../config.json")
	app.ListenForShutdown()
	//||------------------------------------------------------------------------------------------------||
	//|| Initialize Auth
	//||------------------------------------------------------------------------------------------------||
	auth.Init()
	//||------------------------------------------------------------------------------------------------||
	//|| Cors
	//||------------------------------------------------------------------------------------------------||
	app.HTTP["api"].SetDefaults(http.Defaults{
		Cors: http.CORS([]string{
			"https://",
			"http://localhost:5174",
			"*", // optional wildcard for dev/testing — avoid in production
		}),
		Middleware: http.Logger(),
	})
	//||------------------------------------------------------------------------------------------------||
	//|| Start HTTP
	//||------------------------------------------------------------------------------------------------||
	app.HTTP["api"].Start()
	//||------------------------------------------------------------------------------------------------||
	//|| Register Handlers
	//||------------------------------------------------------------------------------------------------||
	handlers.InitRoutes()
	//||------------------------------------------------------------------------------------------------||
	//|| Initialize Stripe
	//||------------------------------------------------------------------------------------------------||
	adapters.InitStripe()
	//||------------------------------------------------------------------------------------------------||
	//|| Keep Alive
	//||------------------------------------------------------------------------------------------------||
	select {}
}
