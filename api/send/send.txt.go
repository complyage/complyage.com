package send

//||------------------------------------------------------------------------------------------------||
//|| Import
//||------------------------------------------------------------------------------------------------||

import (
	"base/adapters" // ← make sure this exists and exports SendText
	"base/template"
	"fmt"
)

//||------------------------------------------------------------------------------------------------||
//|| Init
//||------------------------------------------------------------------------------------------------||

func init() {
	template.Register("verify.sms", "./.assets/html/verify.sms.txt")
}

//||------------------------------------------------------------------------------------------------||
//|| SendVerifyText
//||------------------------------------------------------------------------------------------------||

func SendVerifyText(phone string, code string) (string, error) {

	//||------------------------------------------------------------------------------------------------||
	//|| Template
	//||------------------------------------------------------------------------------------------------||

	tpl := template.Create("verify.sms").Add("VERIFY_CODE", code)

	//||------------------------------------------------------------------------------------------------||
	//|| Modal
	//||------------------------------------------------------------------------------------------------||

	subVerify, err := tpl.Compile()
	if err != nil {
		return "", fmt.Errorf("template rendering failed: %w", err)
	}

	//||------------------------------------------------------------------------------------------------||
	//|| Send SMS
	//||------------------------------------------------------------------------------------------------||

	sent, err := adapters.SendText(phone, subVerify)
	if err != nil {
		return "", err
	}
	return sent, nil
}
