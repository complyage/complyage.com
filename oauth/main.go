package main

import (
	"log"
	"oauth/pages"

	"github.com/complyage/base/encrypted"
	"github.com/complyage/base/keeper"
	"github.com/complyage/base/sites"
	"github.com/complyage/base/verify"
	"github.com/complyage/base/zones"
	"github.com/joho/godotenv"

	"github.com/ralphferrara/aria/app"
	"github.com/ralphferrara/aria/auth"
	"github.com/ralphferrara/aria/base/template"
	"github.com/ralphferrara/aria/http"
	"github.com/ralphferrara/aria/locale"
)

//||------------------------------------------------------------------------------------------------||
//|| Main
//||------------------------------------------------------------------------------------------------||

func main() {
	err := godotenv.Load("../.env")
	if err != nil {
		panic("No .env file found")
	}
	//||------------------------------------------------------------------------------------------------||
	//|| Starting switch-over to aria
	//||------------------------------------------------------------------------------------------------||
	app.Init("../config.json")
	app.ListenForShutdown()
	//||------------------------------------------------------------------------------------------------||
	//|| Cors
	//||------------------------------------------------------------------------------------------------||
	app.HTTP["oauth"].SetDefaults(http.Defaults{
		Cors:       http.CORS([]string{"https://", "http://localhost:5173", "*"}),
		Middleware: http.Logger(),
	})
	//||------------------------------------------------------------------------------------------------||
	//|| Setup Auth DB
	//||------------------------------------------------------------------------------------------------||
	auth.Init(app.SQLDB["main"].DB, app.Config.Auth, ".complyage.com")
	//||------------------------------------------------------------------------------------------------||
	//|| Load Zones
	//||------------------------------------------------------------------------------------------------||
	zones.LoadZones()
	//||------------------------------------------------------------------------------------------------||
	//|| Load Sites
	//||------------------------------------------------------------------------------------------------||
	sites.LoadSites()
	//||------------------------------------------------------------------------------------------------||
	//|| Initialize Locale
	//||------------------------------------------------------------------------------------------------||
	locale.Init("./assets/locale")
	//||------------------------------------------------------------------------------------------------||
	//|| Templates
	//||------------------------------------------------------------------------------------------------||
	//templates.InitTemplates()
	//||------------------------------------------------------------------------------------------------||
	//|| Dev Only
	//||------------------------------------------------------------------------------------------------||
	// Watch for translation changes in dev
	if err := locale.WatchRendered("./assets/locale"); err != nil {
		log.Fatal(err)
	}

	// Watch templates
	if err := template.WatchTemplates("./assets/html", func() {
		// You decide what reload means here: recompile templates, clear cache, etc.
		log.Println("[template] reload triggered")
	}); err != nil {
		log.Fatal(err)
	}

	//||------------------------------------------------------------------------------------------------||
	//|| Static Assets
	//||------------------------------------------------------------------------------------------------||
	app.HTTP["oauth"].Mount("/static/", "public")
	app.HTTP["oauth"].Start()
	//||------------------------------------------------------------------------------------------------||
	//|| Init Routes
	//||------------------------------------------------------------------------------------------------||
	pages.InitRoutes()
	//||------------------------------------------------------------------------------------------------||
	//|| Init Routes
	//||------------------------------------------------------------------------------------------------||
	verify.Init(app.Storages["verifications"], app.SQLDB["main"].DB)
	encrypted.Init(app.Storages["encrypted"])
	keeper.Init(app.CacheRedis["enforce"])
	//||------------------------------------------------------------------------------------------------||
	//|| Keep Alive
	//||------------------------------------------------------------------------------------------------||
	select {}
}
