//||------------------------------------------------------------------------------------------------||
//|| Dependencies
//||------------------------------------------------------------------------------------------------||

import React                  from 'react'
import { Routes, Route }      from 'react-router-dom'

//||------------------------------------------------------------------------------------------------||
//|| Public
//||------------------------------------------------------------------------------------------------||

import Home                   from './pages/public/Home'
import OAuth                  from './pages/public/OAuth'
import Agent                  from './pages/public/Agent'
import Gate                   from './pages/public/Gate'

//||------------------------------------------------------------------------------------------------||
//|| App
//||------------------------------------------------------------------------------------------------||

export default function App() {

      //||------------------------------------------------------------------------------------------------||
      //|| Extract oauth param from URL if exists
      //||------------------------------------------------------------------------------------------------||

      const params            = new URLSearchParams(location.search);
	const oauthParam        = params.get("oauth");
	const appendOauth       = (path: string) => (oauthParam ? `${path}?oauth=${oauthParam}` : path);

      //||------------------------------------------------------------------------------------------------||
      //|| JSX
      //||------------------------------------------------------------------------------------------------||

      return (
		<Routes>
			<Route path="/" element={<Home />} />
                  <Route path="/oauth"  element={<OAuth />} />
                  <Route path="/gate"  element={<Gate />} />            
                  <Route path="/agent"  element={<Agent />} />            
		</Routes>
	);
}