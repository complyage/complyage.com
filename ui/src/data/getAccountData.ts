      import { AccountStatusTypes } from "../interfaces/models/model.account";

      //||------------------------------------------------------------------------------------------------||      
      //|| All Statuses
      //||------------------------------------------------------------------------------------------------||      

      export const AccountStatusLabels: Record<AccountStatusTypes, string> = {
            NONE: "Not Created",
            PNEW: "Created",
            PEND: "Pending",
            VERF: "Verified",
            ACTV: "Active",
            BNND: "Banned",
            RMVD: "Removed",
      };

      //||------------------------------------------------------------------------------------------------||      
      //|| All Statuses
      //||------------------------------------------------------------------------------------------------||      

      export function getAccountStatus(entity: AccountStatusTypes): string {
            return AccountStatusLabels[entity];
      }
