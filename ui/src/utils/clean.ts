      import { isDigit }                  from "./validate";

      //||------------------------------------------------------------------------------------------------||
      //|| Only Digits
      //||------------------------------------------------------------------------------------------------||

      export function onlyDigits (s: string) {
             return s.split("").filter(isDigit).join("")
      };

      //||------------------------------------------------------------------------------------------------||
      //|| Digit and Spaces
      //||------------------------------------------------------------------------------------------------||

      export function digitsAndSpaces(s: string) { 
            return s.split("").filter((ch) => isDigit(ch) || ch === " ").join("");
      }
      
