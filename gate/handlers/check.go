package handlers

import (
	"fmt"
	"net/http"

	"github.com/complyage/base/keeper"
)

//||------------------------------------------------------------------------------------------------||
//|| Response
//||------------------------------------------------------------------------------------------------||

func InitialCheckHandler(w http.ResponseWriter, r *http.Request) {
	//||------------------------------------------------------------------------------------------------||
	//|| Initiate the Zone
	//||------------------------------------------------------------------------------------------------||
	record, err := keeper.Load(r)
	if err != nil {
		fmt.Println("Error initiating keeper:", err)
		return
	}
	//||------------------------------------------------------------------------------------------------||
	//|| Write the Cookie
	//||------------------------------------------------------------------------------------------------||
	record.Respond(w)
}
