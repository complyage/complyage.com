package main

import (
	"fmt"

	"github.com/complyage/base/ips"
	"github.com/complyage/base/keeper"
	"github.com/complyage/base/sites"
	"github.com/complyage/base/zones"
	"github.com/complyage/gate/handlers"

	"github.com/joho/godotenv"
	"github.com/ralphferrara/aria/app"
	"github.com/ralphferrara/aria/http"
)

//||------------------------------------------------------------------------------------------------||
//|| Main
//||------------------------------------------------------------------------------------------------||

func main() {
	//||------------------------------------------------------------------------------------------------||
	//|| Load .env
	//||------------------------------------------------------------------------------------------------||
	err := godotenv.Load("../.env")
	if err != nil {
		panic("No .env file found")
	}
	//||------------------------------------------------------------------------------------------------||
	//|| Starting switch-over to aria
	//||------------------------------------------------------------------------------------------------||
	app.Init("../config.json")
	app.ListenForShutdown()
	//||------------------------------------------------------------------------------------------------||
	//|| Cors
	//||------------------------------------------------------------------------------------------------||
	app.HTTP["gate"].SetDefaults(http.Defaults{
		Cors:       http.CORS([]string{"https://", "http://localhost:5173", "*"}),
		Middleware: http.Logger(),
	})
	//||------------------------------------------------------------------------------------------------||
	//|| Load IPs
	//||------------------------------------------------------------------------------------------------||
	fmt.Println("Loading IP Ranges to memory...")
	//if app.Config.App.Env == "production" {
	ips.LoadIPRanges()
	//}
	fmt.Println("Loaded IP Ranges.")
	//||------------------------------------------------------------------------------------------------||
	//|| Load Zones
	//||------------------------------------------------------------------------------------------------||
	zones.LoadZones()
	//||------------------------------------------------------------------------------------------------||
	//|| Load Sites
	//||------------------------------------------------------------------------------------------------||
	sites.LoadSites()
	//||------------------------------------------------------------------------------------------------||
	//|| Static Assets
	//||------------------------------------------------------------------------------------------------||
	app.HTTP["gate"].Start()
	//||------------------------------------------------------------------------------------------------||
	//|| Init Keeper
	//||------------------------------------------------------------------------------------------------||
	keeper.Init(app.CacheRedis["enforce"])
	//||------------------------------------------------------------------------------------------------||
	//|| Initial
	//||------------------------------------------------------------------------------------------------||
	app.HTTP["gate"].Router.HandleFunc("/v1/check", handlers.InitialCheckHandler).Methods("GET")
	app.HTTP["gate"].Router.HandleFunc("/v1/complyage.js", handlers.GenerateScriptHandler).Methods("GET")
	//||------------------------------------------------------------------------------------------------||
	//|| Manual Check
	//||------------------------------------------------------------------------------------------------||
	app.HTTP["gate"].Router.HandleFunc("/v1/manual", handlers.ManualHandler).Methods("POST")
	//||------------------------------------------------------------------------------------------------||
	//|| Keep Alive
	//||------------------------------------------------------------------------------------------------||
	select {}
}
