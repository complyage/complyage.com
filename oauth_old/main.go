package main

import (
	"base/sites"
	"base/zones"
	"fmt"
	"oauth/handlers"
	"oauth/templates"

	"github.com/joho/godotenv"
	"github.com/ralphferrara/aria/app"
	"github.com/ralphferrara/aria/http"
)

//||------------------------------------------------------------------------------------------------||
//|| Use DB vs In-Memory
//||------------------------------------------------------------------------------------------------||

var UseInMemory bool

//||------------------------------------------------------------------------------------------------||
//|| Main
//||------------------------------------------------------------------------------------------------||

func main() {
	//||------------------------------------------------------------------------------------------------||
	//|| Load Env
	//||------------------------------------------------------------------------------------------------||
	err := godotenv.Load("../.env")
	if err != nil {
		fmt.Println("No .env file found, continuing...")
	}
	//||------------------------------------------------------------------------------------------------||
	//|| Starting switch-over to aria
	//||------------------------------------------------------------------------------------------------||
	app.Init("../config.json")
	app.ListenForShutdown()
	//||------------------------------------------------------------------------------------------------||
	//|| Cors
	//||------------------------------------------------------------------------------------------------||
	app.HTTP["oauth"].SetDefaults(http.Defaults{
		Cors: http.CORS([]string{
			"https://",
			"http://localhost:5174",
			"*",
		}),
		Middleware: http.Logger(),
	})
	//||------------------------------------------------------------------------------------------------||
	//|| Load Zones
	//||------------------------------------------------------------------------------------------------||
	zones.LoadZones()
	//||------------------------------------------------------------------------------------------------||
	//|| Load Sites
	//||------------------------------------------------------------------------------------------------||
	sites.LoadSites()
	//||------------------------------------------------------------------------------------------------||
	//|| Templates
	//||------------------------------------------------------------------------------------------------||
	templates.InitTemplates()
	//||------------------------------------------------------------------------------------------------||
	//|| Static Assets
	//||------------------------------------------------------------------------------------------------||
	app.HTTP["oauth"].Mount("/static/", "public")
	app.HTTP["oauth"].Start()
	//||------------------------------------------------------------------------------------------------||
	//|| Init Routes
	//||------------------------------------------------------------------------------------------------||
	handlers.InitRoutes()
	//||------------------------------------------------------------------------------------------------||
	//|| Keep Alive
	//||------------------------------------------------------------------------------------------------||
	select {}
}
