//|| Escalate
//||------------------------------------------------------------------------------------------------||

func (v *Verification) UpdateStatusVerified(moderator int64) error {
	//||------------------------------------------------------------------------------------------------||
	//|| Set Status
	//||------------------------------------------------------------------------------------------------||
	v.Status = StatusVerified
	v.Updated()
	//||------------------------------------------------------------------------------------------------||
	//|| Add Moderate Info
	//||------------------------------------------------------------------------------------------------||
	v.Moderate = Moderate{
		Type:      MODERATE_TYPE.TwoFactor,
		Status:    MODERATE_STATUS.Approved,
		Moderator: moderator,
		Timestamp: UniversalNow().String(),
	}
	//||------------------------------------------------------------------------------------------------||
	//|| Two Factor Approved
	//||------------------------------------------------------------------------------------------------||
	v.AddStep(STEPTYPES.Moderate, STEPTYPES.Moderate.Description(ModerateTypeTwoFactor.String()))
	//||------------------------------------------------------------------------------------------------||
	//|| Add Step
	//||------------------------------------------------------------------------------------------------||
	v.AddStep(STEPTYPES.StatusChange, STEPTYPES.StatusChange.Description(v.Status.Description()))
	//||------------------------------------------------------------------------------------------------||
	//|| Lock the Encrypted Data
	//||------------------------------------------------------------------------------------------------||
	v.UpdateIdentity()
	fmt.Println(v)
	//||------------------------------------------------------------------------------------------------||
	//|| Lock the Encrypted Data and Update the Database / Storage
	//||------------------------------------------------------------------------------------------------||
	v.SaveEncrypted()
	v.Save(true)
	v.DatabaseUpdate()
	//||------------------------------------------------------------------------------------------------||
	//|| Done
	//||------------------------------------------------------------------------------------------------||
	return nil
}

