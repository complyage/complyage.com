func (v *Verification) UpdateStatusVerified(moderator string) error {
	LogInfo("Update Status Verify: Verified")
	//||------------------------------------------------------------------------------------------------||
	//|| Set Status
	//||------------------------------------------------------------------------------------------------||
	v.Status = StatusVerified
	v.Updated()
	//||------------------------------------------------------------------------------------------------||
	//|| Add Moderate Info
	//||------------------------------------------------------------------------------------------------||
	v.Moderate = Moderate{
		Status:    "APPROVED",
		Moderator: moderator,
		Timestamp: UniversalNow().String(),
	}
	//||------------------------------------------------------------------------------------------------||
	//|| Two Factor Approved
	//||------------------------------------------------------------------------------------------------||
	v.AddStep(STEPTYPES.Moderate, "Approval: "+moderator)
	//||------------------------------------------------------------------------------------------------||
	//|| Add Step
	//||------------------------------------------------------------------------------------------------||
	v.AddStep(STEPTYPES.StatusChange, STEPTYPES.StatusChange.Description(v.Status.Description()))
	//||------------------------------------------------------------------------------------------------||
	//|| Lock the Encrypted Data
	//||------------------------------------------------------------------------------------------------||
	v.UpdateIdentity()
	//||------------------------------------------------------------------------------------------------||
	//|| Lock the Encrypted Data and Update the Database / Storage
	//||------------------------------------------------------------------------------------------------||
	//v.SaveEncrypted()
	v.Save()
	v.DatabaseUpdate()
	//||------------------------------------------------------------------------------------------------||
	//|| Done
	//||------------------------------------------------------------------------------------------------||
	return nil
}

