package verify

//||------------------------------------------------------------------------------------------------||
//|| Main Type Export
//||------------------------------------------------------------------------------------------------||

type Step struct {
	Type      StepType      `json:"type"`
	Timestamp UniversalDate `json:"timestamp"`
	Details   string        `json:"details,omitempty"`
}

//||------------------------------------------------------------------------------------------------||
//|| Initialize Steps
//||------------------------------------------------------------------------------------------------||

func (v *Verification) StepsInit() {
	//||------------------------------------------------------------------------------------------------||
	//|| Initialize Steps
	//||------------------------------------------------------------------------------------------------||
	v.Step = 0
	v.Steps = make([]Step, 0)
	//||------------------------------------------------------------------------------------------------||
	//|| Add Initial Step
	//||------------------------------------------------------------------------------------------------||
	v.AddStep(STEPTYPES.Initial, STEPTYPES.Initial.Description(""))
}

//||------------------------------------------------------------------------------------------------||
//|| Add Step
//||------------------------------------------------------------------------------------------------||

func (v *Verification) AddStep(stepType StepType, details string) {
	//||------------------------------------------------------------------------------------------------||
	//|| Create Step
	//||------------------------------------------------------------------------------------------------||
	step := Step{
		Type:      stepType,
		Timestamp: UniversalNow(),
		Details:   details,
	}
	//||------------------------------------------------------------------------------------------------||
	//|| Append Step
	//||------------------------------------------------------------------------------------------------||
	v.Steps = append(v.Steps, step)
	v.Updated()
}

//||------------------------------------------------------------------------------------------------||
//|| Increment Step
//||------------------------------------------------------------------------------------------------||

func (v *Verification) IncrementStep() {
	//||------------------------------------------------------------------------------------------------||
	//|| Increment Step
	//||------------------------------------------------------------------------------------------------||
	v.Step++
}

//||------------------------------------------------------------------------------------------------||
//|| Count Steps of Type
//||------------------------------------------------------------------------------------------------||

func (v *Verification) CountStepsOfType(stepType StepType) int {
	count := 0
	for _, step := range v.Steps {
		if step.Type == stepType {
			count++
		}
	}
	return count
}
